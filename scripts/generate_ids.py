"""Write ``src/oda_data/_ids.py``: the ``IndicatorId`` literal of every id.

Run after adding, removing, or renaming an indicator in ``oda_data._registry``:

    uv run python scripts/generate_ids.py

``--check`` writes nothing and exits 1 when the file is stale.
``tests/unit/test_registry_dac1.py`` runs the same comparison.
"""

import sys
from collections.abc import Iterable
from pathlib import Path

TARGET = Path(__file__).resolve().parent.parent / "src" / "oda_data" / "_ids.py"

_HEADER = '''"""Every indicator id, for editor completion and type checking.

Generated by ``scripts/generate_ids.py`` from ``oda_data._registry``. Do not
edit by hand; a test fails when this file and the registry disagree.
"""

from typing import Literal

'''


def render(ids: Iterable[str]) -> str:
    """Return the text of ``_ids.py`` for ``ids``, sorted."""
    listed = "".join(f'    "{indicator_id}",\n' for indicator_id in sorted(ids))
    return f"{_HEADER}type IndicatorId = Literal[\n{listed}]\n"


def main(argv: list[str]) -> int:
    """Write ``_ids.py``, or with ``--check`` report whether it is current."""
    from oda_data._registry import INDICATORS

    text = render(INDICATORS)
    if "--check" in argv:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET} is stale; run scripts/generate_ids.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text)
    print(f"wrote {len(INDICATORS)} ids to {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
