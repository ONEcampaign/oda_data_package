"""Write ``docs/docs/reference/indicators.md``: one entry per registered indicator.

The page is built from ``oda_data._registry`` through the same definitions
``oda.describe`` prints, so it cannot drift from the package. Run it after
adding, removing, or changing an indicator:

    uv run python scripts/generate_indicator_docs.py

``--check`` writes nothing and exits 1 when the page is stale.
``tests/docs/test_indicator_reference.py`` runs the same comparison.

The output is already in the layout the repository's mdformat hook writes,
so the hook leaves the page unchanged.
"""

import sys
from collections.abc import Iterable
from pathlib import Path

from oda_data._discover import IndicatorInfo, _eu_institutions_clause, _info
from oda_data._groups import groups
from oda_data._registry import INDICATORS

TARGET = (
    Path(__file__).resolve().parent.parent
    / "docs"
    / "docs"
    / "reference"
    / "indicators.md"
)

#: Each table in page order, with the sentence that opens its section.
TABLES = {
    "dac1": (
        "DAC1",
        "DAC1 holds each provider's official totals, one published line per "
        "kind of flow. Its indicators answer how much a provider gave.",
    ),
    "dac2a": (
        "DAC2A",
        "DAC2A holds what each recipient receives from each provider, net of "
        "repayments. Its indicators answer who received the money.",
    ),
    "crs": (
        "CRS",
        "The Creditor Reporting System holds one row per activity, with its "
        "sector, channel, modality, finance type, and policy markers.",
    ),
    "multisystem": (
        "Multisystem",
        "The Multisystem table holds providers' contributions to each "
        "multilateral organisation and fund.",
    ),
}

_HEADER = """\
# Indicators

<!-- Generated by scripts/generate_indicator_docs.py from oda_data._registry. Do not edit by hand. -->

oda-data has {count} indicators. Each id names who defines it (`oecd` or `one`), the table it reads, and what it counts. `oda.indicators()` returns this list as a DataFrame and `oda.describe(id)` prints one entry.

An indicator's kind says how it is computed. A `sum` adds a value over the table's rows. A `ratio` divides the sum of its numerators by the sum of its denominators, in current USD, so it takes no `unit=`. A `derived` indicator adds or subtracts other indicators, each on the basis of each year. A `method` runs ONE's own code, such as the imputation of multilateral sectors, and then takes units, groups, and `by=` like any other indicator.

A basis marked "2018 on" or "2010 on" raises `BasisRangeError` for earlier years. A caveat that names a basis or years in brackets warns with `OdaDataWarning` when a call reads that basis in those years.
"""


def _code(items: Iterable[str]) -> str:
    return ", ".join(f"`{item}`" for item in items)


def _bases(info: IndicatorInfo) -> str:
    parts = []
    for basis, from_year in info.bases:
        notes = []
        if basis == info.default_basis:
            notes.append("default")
        if from_year is not None:
            notes.append(f"{from_year} on")
        parts.append(f"`{basis}` ({', '.join(notes)})" if notes else f"`{basis}`")
    return ", ".join(parts)


def _providers(info: IndicatorInfo) -> str:
    if info.default_providers is None:
        text = "every official provider in the table, aggregates excluded"
    else:
        group = groups[info.default_providers]
        text = f"{group.label} (`oda.groups.{info.default_providers}`)"
    return text + _eu_institutions_clause(info)


def _values(info: IndicatorInfo) -> str:
    if info.kind == "ratio":
        return "per cent"
    if info.measure != "money":
        return f"millions of {info.measure}, a count that takes no `unit=`"
    return "USD millions unless `unit=` says otherwise"


def _entry(info: IndicatorInfo) -> str:
    lines = [
        f"### `{info.id}`",
        "",
        info.description,
        "",
        f"- Name: {info.name}",
        f"- Kind: {info.kind}",
        f"- Version: {info.version}",
        f"- Dimensions: {_code(info.dimensions)}",
        f"- Bases: {_bases(info)}",
        f"- Default providers: {_providers(info)}",
        f"- Values: {_values(info)}",
        *(f"- Caveat: {caveat}" for caveat in info.caveats),
        "",
        "```python",
        "import oda_data as oda",
        "",
        info.example,
        "```",
    ]
    return "\n".join(lines)


def render() -> str:
    """Return the text of the indicator reference page."""
    infos = [_info(indicator) for indicator in INDICATORS.values()]
    sections = [_HEADER.format(count=len(infos))]
    for table, (label, intro) in TABLES.items():
        found = [info for info in infos if info.table == table]
        found.sort(key=lambda info: not info.id.startswith("oecd."))
        if not found:
            continue
        sections.append(f"## {label}\n\n{intro}\n")
        sections.extend(f"{_entry(info)}\n" for info in found)
    unplaced = sorted({info.table for info in infos} - set(TABLES))
    if unplaced:
        raise SystemExit(f"no section for tables {unplaced}; add them to TABLES")
    return "\n".join(sections)


def main(argv: list[str]) -> int:
    """Write the page, or with ``--check`` report whether it is current."""
    text = render()
    if "--check" in argv:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current != text:
            print(
                f"{TARGET} is stale; run scripts/generate_indicator_docs.py",
                file=sys.stderr,
            )
            return 1
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text)
    print(f"wrote {text.count('### `')} indicators to {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
